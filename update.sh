#!/usr/bin/env bash
# =============================================================================
# alt_celery3 更新脚本
# 功能：
#   1. 从 GitHub 拉取最新代码（git pull）
#   2. 重新构建 Docker 镜像并拉起 docker compose 服务
# 用法：
#   ./update.sh
# =============================================================================

set -euo pipefail

# 脚本所在目录，保证在任意路径下执行都正确
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# -----------------------------------------------------------------------------
# 前置检查
# -----------------------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
    echo "[ERROR] 未找到 docker 命令，请先安装 Docker。" >&2
    exit 1
fi

if ! docker compose version >/dev/null 2>&1; then
    echo "[ERROR] 未找到 docker compose 插件，请先安装 Docker Compose v2。" >&2
    exit 1
fi

if [[ ! -f .env ]]; then
    echo "[WARN] 未找到 .env 文件，请先复制 .env.example 并填写 Redis 连接信息。" >&2
    exit 1
fi

# -----------------------------------------------------------------------------
# 1. 拉取最新代码
# -----------------------------------------------------------------------------
echo "==> 拉取最新代码..."
if git pull --ff-only; then
    echo "==> 代码已更新。"
else
    echo "[ERROR] git pull 失败（可能存在本地改动或网络问题），已中止。" >&2
    exit 1
fi

# -----------------------------------------------------------------------------
# 2. 重新构建并拉起服务（worker / beat / flower）
# -----------------------------------------------------------------------------
echo "==> 重新构建镜像并拉起服务..."
docker compose up -d --build

# -----------------------------------------------------------------------------
# 3. 清理悬空镜像，释放磁盘
# -----------------------------------------------------------------------------
echo "==> 清理悬空镜像..."
docker image prune -f

echo "==> 更新完成。服务状态:"
docker compose ps
